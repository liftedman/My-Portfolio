import { defineArrayMember, defineField, defineType } from 'sanity';

export const project = defineType({
  name: 'project',
  title: 'Project',
  type: 'document',
  groups: [
    { name: 'basics', title: 'Basics', default: true },
    { name: 'media', title: 'Images' },
    { name: 'details', title: 'Details' },
    { name: 'caseStudy', title: 'Case study' },
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Project name',
      type: 'string',
      group: 'basics',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'Page address',
      description: 'Used in the link: yoursite.com/projects/<this>. Click "Generate" to make it from the name.',
      type: 'slug',
      group: 'basics',
      options: { source: 'title', maxLength: 64 },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'shortDescription',
      title: 'One-line summary',
      description: 'Shown under the project card. Keep it to one sentence.',
      type: 'string',
      group: 'basics',
      validation: (rule) => rule.required().max(140),
    }),
    defineField({
      name: 'status',
      title: 'Status',
      type: 'string',
      group: 'basics',
      options: {
        list: [
          { title: 'Live — people can visit it', value: 'live' },
          { title: 'Private — not public', value: 'private' },
          { title: 'Archived — no longer online', value: 'archived' },
        ],
        layout: 'radio',
      },
      initialValue: 'live',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'link',
      title: 'Live website / app link',
      description: 'Only shown when the status is "Live".',
      type: 'url',
      group: 'basics',
      hidden: ({ parent }) => parent?.status !== 'live',
    }),
    defineField({
      name: 'statusNote',
      title: 'Why there is no link',
      description: 'A short, honest note shown instead of a link, e.g. "The client retired this deployment in 2025."',
      type: 'text',
      rows: 3,
      group: 'basics',
      hidden: ({ parent }) => parent?.status === 'live',
    }),
    defineField({
      name: 'github',
      title: 'GitHub link (optional)',
      type: 'url',
      group: 'basics',
    }),
    defineField({
      name: 'order',
      title: 'Position',
      description: '1 shows first, 2 second, and so on.',
      type: 'number',
      group: 'basics',
      initialValue: 99,
    }),

    defineField({
      name: 'mainImage',
      title: 'Cover image',
      description: 'The big image on the project card. Landscape works best (16:10).',
      type: 'image',
      group: 'media',
      options: { hotspot: true },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'gallery',
      title: 'More screenshots',
      description: 'Shown on the case study page. Drag to reorder.',
      type: 'array',
      group: 'media',
      of: [defineArrayMember({ type: 'image', options: { hotspot: true } })],
      options: { layout: 'grid' },
    }),

    defineField({
      name: 'category',
      title: 'Category',
      type: 'string',
      group: 'details',
      options: {
        list: [
          { title: 'Mobile', value: 'mobile' },
          { title: 'Web', value: 'web' },
          { title: 'Design', value: 'design' },
          { title: 'Backend', value: 'backend' },
        ],
        layout: 'radio',
        direction: 'horizontal',
      },
      initialValue: 'web',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'year',
      title: 'Year',
      type: 'number',
      group: 'details',
      initialValue: () => new Date().getFullYear(),
      validation: (rule) => rule.required().min(2000).max(2100),
    }),
    defineField({
      name: 'role',
      title: 'Your role',
      description: 'e.g. "Full-Stack Developer"',
      type: 'string',
      group: 'details',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'description',
      title: 'What I built',
      description: 'A short paragraph about the project.',
      type: 'text',
      rows: 5,
      group: 'details',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'technologies',
      title: 'Technologies',
      description: 'Type one and press Enter.',
      type: 'array',
      group: 'details',
      of: [defineArrayMember({ type: 'string' })],
      options: { layout: 'tags' },
    }),
    defineField({
      name: 'highlights',
      title: 'Key highlights',
      description: 'One point per line. A real number ("100+ users in month one") beats a feature.',
      type: 'array',
      group: 'details',
      of: [defineArrayMember({ type: 'string' })],
    }),

    defineField({
      name: 'caseStudy',
      title: 'Case study (all optional)',
      description: 'Each part only appears on the site when you fill it in.',
      type: 'object',
      group: 'caseStudy',
      fields: [
        defineField({ name: 'problem', title: 'The problem', type: 'text', rows: 3 }),
        defineField({ name: 'constraints', title: 'Constraints', type: 'text', rows: 3 }),
        defineField({ name: 'decisionTitle', title: 'A hard decision — heading', type: 'string' }),
        defineField({ name: 'decisionBody', title: 'A hard decision — explanation', type: 'text', rows: 4 }),
        defineField({ name: 'outcome', title: 'Outcome', type: 'text', rows: 3 }),
      ],
    }),
  ],
  orderings: [
    { title: 'Position', name: 'orderAsc', by: [{ field: 'order', direction: 'asc' }] },
    { title: 'Newest', name: 'yearDesc', by: [{ field: 'year', direction: 'desc' }] },
  ],
  preview: {
    select: { title: 'title', status: 'status', year: 'year', media: 'mainImage' },
    prepare: ({ title, status, year, media }) => ({
      title,
      subtitle: [year, status].filter(Boolean).join(' · '),
      media,
    }),
  },
});
